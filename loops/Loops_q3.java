//Question3- print sum of number till 100
public class Loops_q3 {
    public static void main(String[] args) {
        System.out.println("Sum of numbers till 100");
        int sum = 0;
        for (int i = 1; i <=100 ; i++) {
            sum += i;
        }
        System.out.println("The sum is " +sum);
    }
}
